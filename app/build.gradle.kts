        unitTests.isReturnDefaultValues = true
    }
    lint {
        // Lint findings are published as a report artifact; they don't block the APK.
        abortOnError = false
        checkReleaseBuilds = false
    }
    packaging {
        resources.excludes += "/META-INF/{AL2.0,LGPL2.1}"
    }
